#!/usr/bin/env python3
"""Build the P4 open loading fixture into a DERIVED world.

WHY A DERIVED WORLD
`assets/world_p3_cell.xml` is GENERATED by `experiments/merge_world.py` and is FROZEN. Three
measured facts make the P4 steps 4 and 5 impossible in it (`reports/p4-count-01`):

  1. REACH      the tray sits at local x +1.7264 m from `a_link0`; IK converges to 0.780 and fails
                at 0.820 (`reports/p4-arm-01`), so the tray is 2.2x out of reach;
  2. LID        `c_visual_marker` is a plate at rel-z [+0.025, +0.027] spanning all three cells, and a
                part on the deck tops out at +0.020 -- so a part renders ZERO segmentation pixels at
                every angle tested, including 4.1 degrees off vertical;
  3. MERGE      the tray floor's top is 0.20998, and the segmenter keeps only points above
                `bench_z + 0.5*min(g)` = 0.2075. So the floor is 2.5 mm ABOVE that plane, the part
                stands on the floor, and the two are 4-connected in the image: one 3772 px blob whose
                mean colour is the tray's. The part's own colour never reaches the classifier.

The decision (`D115`) is to add an OPEN loading fixture that lies inside the arm's reach, rather than
reshape the tray (which would invalidate every report citing the frozen world) or abandon the optical
read. This script builds it.

WHAT THE FIXTURE IS -- AND THE ONE PIECE THAT HAD TO CHANGE
It is the TRAY'S OWN CROSS-SECTION stood on the bench: same deck half-extents, same wall and rib
thicknesses, same partition offsets. Every one of those is READ OFF THE TRAY at build time, not
typed, so the two fixtures cannot drift apart in cell convention.

The one deliberate difference is the floor. The tray's floor is a plate INSIDE its walls; the fixture
has no raised floor at all and its cells rest on the bench, because a floor above the segmentation
plane is exactly what fact 3 measures. Its floor geom is the thinnest plate that still reads as a
deck, with its top at 40% of the way to the plane, which leaves 4.5 mm of margin.

The ribs are half a part's height, so a part placed in a cell always towers above its own rib. The
ribs and walls DO stand above the plane and so appear in the mask -- grey (`chroma_class` needs a
1.5x channel ratio), which is why they can never be mistaken for a part. That is checked, not
assumed: see `reports/p4-arm-02` row `the_fixture_is_never_mistaken_for_a_part`.

NOT CLAIMED: that a 12.5 mm rib retains a part during transport. Retention is `P4-BELT-03`, and `G-2`
already measured that the deck's blade cannot lift at all.
"""
import argparse
import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))
sys.path.insert(0, str(ROOT / 'experiments'))

import mujoco  # noqa: E402
import numpy as np  # noqa: E402

import probe_p3_vision as PV  # noqa: E402
from workcell.tray import derive_cells  # noqa: E402

SOURCE = ROOT / 'assets' / 'world_p3_cell.xml'
TARGET = ROOT / 'assets' / 'world_p4_cell.xml'

ARM_BODY, TABLE, PART, TRAY, FIXTURE = 'a_link0', 'a_table', 'a_payload', 'c_payload', 'p_fixture'

#: DECLARED in-reach pose. `reports/p4-arm-01` measured IK converging at 0.780 m and failing at
#: 0.820 m from `a_link0`, so 0.70 leaves 80 mm of margin; the cell rows are +-0.1534 m off this
#: axis, which puts the three cell centres at radii 0.7000 / 0.7166 m.
FIXTURE_LOCAL_X = 0.70
FIXTURE_LOCAL_Y = 0.00
#: DECLARED: the floor top as a fraction of the way to the segmentation plane. The plane is
#: `bench_z + 0.5 * min(part half-extents)` -- read off the frozen segmenter, not typed.
FLOOR_TOP_FRACTION = 0.40
GREY = '0.5 0.5 0.5 1'


def trap(name):
    """The tray's geom of that name -> (half-extents, world centre). Read, never typed."""
    def look(model, data):
        gid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_GEOM, name)
        if gid < 0:
            raise SystemExit('the tray has no geom %r, so the fixture cannot copy its section' % name)
        return np.asarray(model.geom_size[gid], float), np.asarray(data.geom_xpos[gid], float)
    return look


def derive(model, data):
    """Everything the fixture is made of, read off the model in hand."""
    bench_top, _roi = PV.bench_geometry(model, data)
    g = np.asarray(PV.part_size(model), float)
    cells = derive_cells(model, data, TRAY)
    arm = np.asarray(data.xpos[model.body(ARM_BODY).id], float)

    floor_size, floor_c = trap('c_tray_floor')(model, data)
    wall_x_size, _ = trap('c_tray_wall_xp')(model, data)
    wall_y_size, _ = trap('c_tray_wall_yp')(model, data)
    rib_size, _ = trap('c_tray_divider_1')(model, data)

    deck_half_x, deck_half_y = float(cells['deck']['size'][0]), float(cells['deck']['size'][1])
    wall_t = float(wall_x_size[0])                    # 0.004
    rib_t = float(rib_size[1])                        # 0.003
    inner_half_x = float(wall_y_size[0])              # 0.057 -- a y-wall spans between the x-walls
    partitions = [float(p) for p in cells['partitions']]
    plane_above_bench = 0.5 * float(np.min(g))
    floor_top = FLOOR_TOP_FRACTION * plane_above_bench

    return {
        'bench_top': float(bench_top), 'g': g, 'arm_xy': arm[:2], 'deck_half_x': deck_half_x,
        'deck_half_y': deck_half_y, 'wall_t': wall_t, 'rib_t': rib_t,
        'inner_half_x': inner_half_x, 'partitions': partitions,
        'plane_above_bench': plane_above_bench, 'floor_top': floor_top,
        'wall_half_z': float(g[2]),                   # a wall as tall as a part
        'rib_half_z': 0.5 * float(g[2]),              # so a part always towers above its own rib
        'floor_half_z': 0.5 * floor_top,              # a plate lying ON the bench, top at floor_top
        'fixture_xy': (float(arm[0]) + FIXTURE_LOCAL_X, float(arm[1]) + FIXTURE_LOCAL_Y),
        'cells': cells,
    }


def block(d):
    """The XML body for the fixture, with every number's derivation in the comment above it."""
    fx, fy = d['fixture_xy']
    z0 = d['bench_top']
    L = []
    L.append('    <!-- Added by experiments/build_p4_cell_world.py -- the P4 OPEN loading fixture.')
    L.append('         This body is the TRAY\'S OWN CROSS-SECTION stood on the bench: deck half-extents')
    L.append('         %.4f x %.4f, wall/rib thickness %.4f/%.4f and the partition offsets %s are all'
             % (d['deck_half_x'], d['deck_half_y'], d['wall_t'], d['rib_t'],
                [round(p, 5) for p in d['partitions']]))
    L.append('         read off c_payload at build time, so both fixtures share one cell convention.')
    L.append('         pos = a_link0 + (%.2f, %.2f) in x/y, z = the bench top %.4f.' %
             (FIXTURE_LOCAL_X, FIXTURE_LOCAL_Y, z0))
    L.append('         There is NO raised floor: the tray\'s floor top sits at %.5f, which is ABOVE the'
             % (d['bench_top'] + 0.00998))
    L.append('         segmenter\'s plane bench_z + 0.5*min(part) = %.5f, which 4-connects a part to the'
             % (d['bench_top'] + d['plane_above_bench']))
    L.append('         floor it stands on (measured: one blob, the part\'s colour unrecoverable). This')
    L.append('         floor\'s top is %.4f, i.e. %.4f m below that plane.'
             % (z0 + d['floor_top'], d['plane_above_bench'] - d['floor_top']))
    L.append('         Grey on purpose: chroma_class needs a 1.5x channel ratio, so the walls and ribs')
    L.append('         that DO stand above the plane can never be a part candidate. -->')
    L.append('    <body name="%s" pos="%.5f %.5f %.5f">' % (FIXTURE, fx, fy, z0))

    def geom(name, size, pos):
        L.append('      <geom name="%s" type="box" size="%s" pos="%s" rgba="%s"/>'
                 % (name, ' '.join('%.5f' % v for v in size),
                    ' '.join('%.5f' % v for v in pos), GREY))

    hx, hy = d['deck_half_x'], d['deck_half_y']
    geom('p_fixture_floor', (hx, hy, d['floor_half_z']), (0.0, 0.0, d['floor_half_z']))
    cx = hx - d['wall_t']
    geom('p_fixture_wall_xp', (d['wall_t'], hy, d['wall_half_z']), (cx, 0.0, d['wall_half_z']))
    geom('p_fixture_wall_xn', (d['wall_t'], hy, d['wall_half_z']), (-cx, 0.0, d['wall_half_z']))
    cy = hy - d['wall_t']
    geom('p_fixture_wall_yp', (d['inner_half_x'], d['wall_t'], d['wall_half_z']),
         (0.0, cy, d['wall_half_z']))
    geom('p_fixture_wall_yn', (d['inner_half_x'], d['wall_t'], d['wall_half_z']),
         (0.0, -cy, d['wall_half_z']))
    for k, p in enumerate(d['partitions']):
        geom('p_fixture_rib_%d' % k, (d['inner_half_x'], d['rib_t'], d['rib_half_z']),
             (0.0, p, d['rib_half_z']))
    L.append('    </body>')
    return '\n'.join(L)


def build(text, d):
    anchor = '  </worldbody>'
    if text.count(anchor) != 1:
        raise SystemExit('REFUSED: %d matches for the worldbody close' % text.count(anchor))
    return text.replace(anchor, block(d) + '\n' + anchor)


def checks(source_model, source_data, text_out, d):
    """Compile BEFORE writing, and assert the fixture changed nothing else.

    The check file has to sit NEXT TO the source: the merged world references its meshes by
    relative path (`t800/robot/t800/meshes/...`), so compiling a copy from /tmp fails to find
    them. It is written under the same name the merge script uses for its own dry runs and is
    removed in the `finally`.
    """
    tmp = SOURCE.parent / '_world_p4_build_check.xml'
    tmp.write_text(text_out, encoding='utf-8')
    try:
        m = mujoco.MjModel.from_xml_path(str(tmp))
    finally:
        tmp.unlink()
    dd = mujoco.MjData(m)
    dd.qpos[:] = m.key_qpos[0]
    mujoco.mj_forward(m, dd)
    out = []
    same = []
    if m.nq != source_model.nq:
        raise SystemExit('REFUSED: nq changed %d -> %d' % (source_model.nq, m.nq))
    if m.nkey != source_model.nkey:
        raise SystemExit('REFUSED: nkey changed')
    for body in (ARM_BODY, TABLE, PART, TRAY):
        a = np.asarray(source_data.xpos[source_model.body(body).id], float)
        b = np.asarray(dd.xpos[m.body(body).id], float)
        if not np.array_equal(a, b):
            raise SystemExit('REFUSED: %s moved %s -> %s' % (body, a, b))
        same.append(body)
    out.append('nq %d unchanged; nkey %d unchanged; %s did not move'
               % (m.nq, m.nkey, '/'.join(same)))
    top2, _ = PV.bench_geometry(m, dd)
    if abs(top2 - d['bench_top']) > 1e-12:
        raise SystemExit('REFUSED: the bench top moved')

    fid = m.body(FIXTURE).id
    gids = [g for g in range(m.ngeom) if int(m.geom_bodyid[g]) == fid]
    if len(gids) != 7:
        raise SystemExit('REFUSED: expected 7 fixture geoms, found %d' % len(gids))
    tops = {}
    for g in gids:
        nm = mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_GEOM, g)
        tops[nm] = float(dd.geom_xpos[g][2] + m.geom_size[g][2])
    plane = d['bench_top'] + d['plane_above_bench']
    floor_top = tops['p_fixture_floor']
    if floor_top > plane:
        raise SystemExit('REFUSED: the floor top %.5f is not below the plane %.5f'
                         % (floor_top, plane))
    for nm in ('p_fixture_wall_xp', 'p_fixture_wall_yp', 'p_fixture_rib_0', 'p_fixture_rib_1'):
        if tops[nm] <= floor_top:
            raise SystemExit('REFUSED: %s does not stand above the floor' % nm)
    out.append('segmentation plane %.5f; floor top %.5f (%.5f m below it); the floor is NOT in the '
               'mask' % (plane, floor_top, plane - floor_top))

    cells = derive_cells(m, dd, FIXTURE)
    if len(cells['cells']) != len(d['cells']['cells']):
        raise SystemExit('REFUSED: the fixture derives %d cells, the tray derives %d'
                         % (len(cells['cells']), len(d['cells']['cells'])))
    for a, b in zip(cells['cells'], d['cells']['cells']):
        if abs(float(a['width']) - float(b['width'])) > 1e-9:
            raise SystemExit('REFUSED: cell %d width %.6f vs the tray\'s %.6f'
                             % (a['index'], a['width'], b['width']))
    if cells['axis'] != d['cells']['axis']:
        raise SystemExit('REFUSED: the fixture is divided on a different axis')
    out.append('derive_cells(p_fixture) -> %d cells, widths %s, divided on %s -- identical to the '
               'tray\'s' % (len(cells['cells']), [round(float(c['width']), 5) for c in cells['cells']],
                            'xy'[cells['axis']]))
    out.append('cell centres, radius from %s: %s' %
               (ARM_BODY, [round(float(np.hypot(cells['deck']['centre'][0] + 0.0 - d['arm_xy'][0],
                                              float(c['centre']))), 5)
                           for c in cells['cells']]))
    return m, dd, cells, out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true',
                    help='rebuild in memory and compare with the file on disk')
    args = ap.parse_args(argv)

    text = SOURCE.read_text(encoding='utf-8')
    model = mujoco.MjModel.from_xml_path(str(SOURCE))
    data = mujoco.MjData(model)
    data.qpos[:] = model.key_qpos[0]
    mujoco.mj_forward(model, data)
    d = derive(model, data)
    text_out = build(text, d)
    _m, _dd, cells, lines = checks(model, data, text_out, d)

    if args.check:
        if not TARGET.exists():
            print('CHECK FAILED: %s does not exist' % TARGET)
            return 1
        have = TARGET.read_text(encoding='utf-8')
        print('check: on-disk == rebuilt: %s' % (have == text_out))
        return 0 if have == text_out else 1

    TARGET.write_text(text_out, encoding='utf-8')
    for L in lines:
        print('  %s' % L)
    print()
    print('source %s  %s' % (SOURCE.name, _sha(SOURCE.read_bytes())))
    print('target %s  %s' % (TARGET.name, _sha(TARGET.read_bytes())))
    return 0


def _sha(b):
    import hashlib
    return hashlib.sha256(b).hexdigest()[:16]


if __name__ == '__main__':
    raise SystemExit(main())
