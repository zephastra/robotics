"""W0: the integration baseline -- what a new writer must know before touching anything.

The guidance asks for a baseline document with source/config/asset/world fingerprints, the real
file name and format of each piece of evidence, the scope of each historical PASS, the version
mismatches, and whether it is safe to take over. Every number here is READ, and the ones that could
drift (hashes, counts, evidence states) are recomputed on every run, with `--check` comparing.

What is deliberately NOT derived (and is marked as such inside the document, the same way
`make_handoff.py` marks its own): the list of open boundaries, because "what the evidence does not
support" is a judgement. A generator should not pretend its opinions are measurements.

The report index and the claim record are IMPORTED from `make_handoff.py` rather than reimplemented,
so the two documents cannot disagree about what a run's evidence file is called.
"""
import argparse
from datetime import date
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'experiments'))

import make_handoff  # noqa: E402

HISTORY = ROOT / 'docs' / 'history'
FREEZE = ROOT / 'config' / 'p3_freeze.json'
STAMP_COVERED = 3          # digits of each sha256 shown, so the document stays readable

#: The files whose identity a new writer has to know. Grouped because they fail differently:
#: a changed world or config invalidates a run, a changed judge invalidates a verdict.
FINGERPRINT_GROUPS = (
    ('the core (no ROS: this is what makes "core does not depend on ROS" testable)',
     ('src/workcell/*.py',)),
    ('the generators and judges (a change here invalidates verdicts, not worlds)',
     ('experiments/*.py',)),
    ('the tests', ('tests/*.py',)),
    ('the frozen configuration and assets', ('config/*.yaml', 'config/*.json',
                                            'assets/world*s/*.xml', 'assets/world*.xml',
                                            'assets/maps/*')),
)

#: DECLARED, not computed. Each line is a fact about the project that no hash can show, written
#: here so that a new writer meets it before choosing a work package.
OPEN_BOUNDARIES = """\
- **`P1-ENV-01`** is `DONE` on the board, which means *the environment was frozen with a DECLARED
  STAND-IN chassis* -- and `config/p3_freeze.json` lists `the AMR model -- not selected yet
  (P1-ENV-01)` under `not_frozen`. Both statements are true and they read as opposites, so: the
  chassis is a self-made differential-drive stand-in, and **the model is not selected**. Decide it
  before any docking contract is frozen, or the contract is written against a stand-in.
- **The AMR has no camera.** The P3 vision camera is added by its probe through `MjSpec`, and its
  calibration used the simulator's geom labels -- an oracle a real camera does not have. A relative
  docking sensor does not exist yet.
- **`P1-N`'s arrival number is a localisation number, not a control number** (`D062`): the vehicle
  stops within ~0.01 m of where it BELIEVES the goal is, and AMCL's belief is 0.05-0.16 m out. The
  0.25 m limit is 0.15 m of nav2 contract plus a 0.10 m localisation budget, and AMCL's p95 alone
  (0.119-0.163 m) eats that budget, so the check fails roughly two times in five BY CONSTRUCTION.
- **There is no git repository.** `AGENTS.md` mentions local git as a checkpoint; there is none, so
  there is no diff, no rollback, and no ownership evidence from a commit. Edits keep a
  `.bak_<tag>_<stamp>` copy and the reason is recorded in `docs/DECISIONS.md`.
- **The simulator has no seed control.** The same command and config produced 0.225-0.283 m across
  four runs at one goal (sample sd 25.4 mm). Recording a seed would imply a reproducibility the
  project does not have; the spread comes from timing, not from an RNG.
"""


def sha(path, digits=STAMP_COVERED):
    return hashlib.sha256(path.read_bytes()).hexdigest()[:digits] if digits else \
        hashlib.sha256(path.read_bytes()).hexdigest()


def glob_group(pattern):
    files = sorted(ROOT.glob(pattern))
    if not files:
        return None, []
    digest = hashlib.sha256()
    for item in files:
        digest.update(item.name.encode())
        digest.update(item.read_bytes())
    return digest.hexdigest()[:STAMP_COVERED], files


def render(day):
    rows, conflicts = make_handoff.parse_board()
    claims, all_claims, claim_note = make_handoff.parse_claims()
    lines = [
        '<!-- GENERATED by experiments/make_baseline.py -- do not hand-edit. -->',
        f'# 集成基线 / integration baseline -- {day}', '',
        '> **GENERATED.** Regenerate with `./.venv/bin/python experiments/make_baseline.py`;',
        '> verify with `--check`. The fingerprints, the report index and the claim record are read',
        '> on every run. The section "open boundaries" is a judgement and is declared as one.',
        '',
        '## 1. The W0 record (who, what, what may be touched, and when it is done)', '',
        '| field | value |', '|---|---|',
        f'| work package | W0 baseline + W1 identity/aggregation/report index (`{day}`) |',
        '| writer | the assistant, under the user\'s "按指导书执行" authorisation |',
        '| goal | make the acceptance trustworthy BEFORE making the first logistics chain real |',
        '| NON-goals | no navigation tuning, no mechanism change, no threshold relaxation, no new '
        'sensor, no order/ledger feature work |',
        '| files it may touch | `experiments/evaluate_p3_nav.py`, `experiments/make_handoff.py`, '
        '`tests/*.py`, `docs/*`, `docs/history/*` |',
        '| budget | one round; no long physics run (the re-judge re-reads existing reports) |',
        '| exit gate | the three defects each have a test that fails before and passes after; no '
        'identity is derived from a run id; a missing required check cannot pass; a missing report '
        'is classified rather than called absent; the original reports are untouched |',
        '',
        '## 2. Fingerprints', '',
        '| group | files | digest |', '|---|---|---|',
    ]
    for label, patterns in FINGERPRINT_GROUPS:
        digests, names = [], []
        for pattern in patterns:
            digest, files = glob_group(pattern)
            if digest:
                digests.append(digest)
                names += files
        combined = hashlib.sha256(''.join(digests).encode()).hexdigest()[:STAMP_COVERED]
        lines.append(f'| {label} | {len(names)} | `{combined}` |')
    lines += ['', '| artefact | sha256 (first 16) | note |', '|---|---|---|']
    for label, path in (
            ('the P3 judged world', 'assets/world_p3_cell.xml'),
            ('the P3 navigation arena (bare)', 'assets/worlds/world_p3_nav.xml'),
            ('the P3 navigation arena (loaded)', 'assets/worlds/world_p3_nav_loaded.xml'),
            ('the navigation arena layout', 'assets/worlds/world_p3_nav.layout.json'),
            ('the P1 arena used by P1-N', 'assets/worlds/world_n_probe.xml'),
            ('the navigation map', 'assets/maps/p3_nav.yaml'),
            ('the navigation map image', 'assets/maps/p3_nav.pgm'),
            ('the frozen nav2 params (P3)', 'config/nav2_p3_nav.yaml'),
            ('the board', 'docs/TASK_BOARD.md'),
            ('the decisions', 'docs/DECISIONS.md'),
            ('the claim record', 'docs/CLAIMS.md'),
            ('the freeze', 'config/p3_freeze.json')):
        full = ROOT / path
        lines.append(f'| `{path}` | `{sha(full, 16) if full.is_file() else "ABSENT"}` | '
                     f'{full.stat().st_size if full.is_file() else 0} bytes |')
    if FREEZE.is_file():
        frozen = json.loads(FREEZE.read_text(encoding='utf-8'))
        lines += ['', f"- `config/p3_freeze.json`: **{len(frozen['artefacts'])} artefacts**, "
                      f"**{len(frozen['code'])} scripts**, **{len(frozen['thresholds'])} "
                      f"thresholds**."]

    lines += ['', '## 3. The report index: what each evidence directory actually contains', '',
              '| stage | what | run | state | verdict | file |', '|---|---|---|---|---|---|']
    problems = []
    for stage, what, path, declared in make_handoff.EVIDENCE:
        ev = make_handoff.run_evidence(path, declared)
        if ev['state'] not in ('OK', 'INDEX'):
            problems.append((path, ev))
        lines.append(f"| {stage} | {what} | `{path}` | {ev['state']} | "
                     f"{ev.get('verdict') or '--'} | `{ev['file'] or '--'}` |")
    lines += ['', '**States**: `OK` a verdict was read (the field is named in the file), `INDEX` '
              'an index over cases rather than one verdict, `DIR_MISSING` the directory is not '
              'there, `FILE_MISSING` the directory is there and the declared file is not, '
              '`UNPARSEABLE` it will not parse, `NO_VERDICT` it parses and carries no verdict at '
              'all. Answering all of those with one word was the defect this index replaces.', '']
    if problems:
        lines += ['### Evidence that needs attention', '']
        for path, ev in problems:
            lines.append(f"- **{ev['state']}** `{path}` -- {ev['detail']}")
        lines.append('')

    lines += ['## 4. Who holds what', '',
              '(from the hand-written `docs/CLAIMS.md`; a derived "next task" is a recommendation, '
              'not a claim)', '']
    if claim_note:
        lines.append(f'- {claim_note}')
    elif claims:
        for claim in claims:
            lines.append(f"- ACTIVE: `{claim['task']}` -- {claim['by']} since {claim['at']}")
    else:
        lines.append('- ACTIVE: **none** -- no unreleased claim is recorded.')
    lines.append(f'- the claim record holds {len(all_claims)} row(s) in total, '
                 f'{len(all_claims) - len(claims)} released')
    done = [row for row in rows if row['status'] == 'DONE']
    open_rows = [row for row in rows if row['status'] != 'DONE']
    lines += ['', f'- board: {len(done)} of {len(rows)} rows are DONE and {len(open_rows)} are '
                  f'open. **That is a count of rows, not a completion percentage**: the rows are '
                  f'not equal units of work and the guidance says so explicitly.', '']
    if conflicts:
        lines += ['### ⚠️ Board ids that disagree with themselves', '']
        for tid, statuses in sorted(conflicts.items()):
            lines.append(f'- `{tid}` appears with {statuses}')
        lines.append('')

    lines += ['## 5. Open boundaries -- DECLARED, not computed', '',
              'Read this with the numbers above, never instead of them.', '', OPEN_BOUNDARIES, '']

    blockers = bool(conflicts) or bool(problems)
    lines += ['## 6. Can a new writer take over?', '',
              f"- fingerprints: present ({len(FINGERPRINT_GROUPS)} groups read, all hashes above "
              f"are of files on disk right now)",
              f"- board self-consistency: {'FAILED -- see above' if conflicts else 'ok, no id has '
               'two statuses'}",
              f"- evidence index: {'NEEDS ATTENTION -- see above' if problems else 'every declared '
               'directory resolved to a verdict or an index'}",
              f"- claim record: {'present' if not claim_note else 'MISSING'}",
              '',
              ('**Verdict: SAFE TO TAKE OVER for the W2-W5 work packages, with the boundaries in '
               'section 5 in hand.** The verdict is about the EVIDENCE, not about the project '
               'being finished.' if not blockers else
               '**Verdict: NOT SAFE until the items above are resolved.** A generated document that '
               'reports a contradiction must not also report that all is well.'),
              '',
              '### What this baseline did NOT check', '',
              '- it did not re-run a single experiment: it reads what is on disk;',
              '- it did not verify that a `DONE` row\'s evidence supports that row\'s CLAIM, only '
              'that the evidence file exists and carries some verdict;',
              '- it did not look at 001-009, which is out of scope for this project;',
              '- it did not confirm that no 010 process is currently running (see section 1 of the '
              'guidance: check `/proc`, do not assume from a document).',
              '']
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--date', default=None, help='defaults to today')
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()

    if args.check:
        existing = sorted(HISTORY.glob('INTEGRATION_BASELINE_*.md'))
        if not existing:
            print('[FAIL] no baseline exists; run without --check to write one')
            return 1
        target = existing[-1]
        # regenerate for the date RECORDED IN THE FILE, so that a new day does not fail the check:
        # the document is a snapshot, and only its content is under test here
        found = re.search(r'INTEGRATION_BASELINE_(\d{4})(\d{2})(\d{2})', target.name)
        day = (f'{found.group(1)}-{found.group(2)}-{found.group(3)}'
               if found else date.today().isoformat())
        text = render(day)
        if target.read_text(encoding='utf-8') != text:
            print(f'[FAIL] {target.relative_to(ROOT)} is out of date; regenerate and review the diff')
            return 1
        print(f'[OK] {target.relative_to(ROOT)} matches the fingerprints and the evidence on disk')
        return 0

    day = args.date or date.today().isoformat()
    target = HISTORY / f'INTEGRATION_BASELINE_{day.replace("-", "")}.md'
    target.parent.mkdir(parents=True, exist_ok=True)
    text = render(day)
    target.write_text(text, encoding='utf-8')
    print(f'wrote {target.relative_to(ROOT)} ({len(text.splitlines())} lines)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
