def test_a_world_that_changed_after_the_run_is_a_failure(tmp_path):
    """Evidence about a different machine is not evidence."""
    reports = synth(tmp_path, 'a_stale', [{}], records=healthy_records())
    report = json.loads((reports / 'a_stale' / 'report.json').read_text())
    report['world_sha256'] = '0' * 64
    (reports / 'a_stale' / 'report.json').write_text(json.dumps(report))
    done = subprocess.run([sys.executable, str(JUDGE), '--run-id', 'a_stale',
                           '--reports-dir', str(reports)], capture_output=True, text=True)
    payload = json.loads((reports / 'a_stale' / 'acceptance.json').read_text())
    assert verdicts(payload)['nothing attaches the payload to the gripper'] == 'FAIL'
    assert done.returncode == 1


