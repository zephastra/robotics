def test_the_grasp_frame_is_a_constant_of_the_model_not_a_typed_number():
    """Derived, and independent of the pose it is measured in."""
    import mujoco
    model, data = rig.load(rig.DEFAULT_FRICTION)
    b = rig.ids(model)
    seen = []
    for seed in (model.key_qpos[0][:7], list(model.key_qpos[0][:7] + 0.3)):
        data.qpos[b['arm_qadr']] = seed
        mujoco.mj_forward(model, data)
        seen.append(rig.grasp_local_offset(model, data))
    assert max(abs(a - c) for a, c in zip(seen[0], seen[1])) < 1e-12, (
        'the grasp offset must not depend on the pose')
    # and it must equal the pad-centre midpoint recomputed from world geometry
    hand = b['hand']
    R = data.xmat[hand].reshape(3, 3)
    p = data.xpos[hand]
    centres = [data.geom_xpos[rig._pad_geom(model, s)]
               for s in ('left_finger', 'right_finger')]
    expect = R.T @ ((centres[0] + centres[1]) / 2.0 - p)
    assert max(abs(a - c) for a, c in zip(seen[0], expect)) < 1e-12
    assert seen[0][0] == pytest.approx(0.0, abs=1e-9) and \
        seen[0][1] == pytest.approx(0.0, abs=1e-9), (
            'the grasp frame must sit on the closing axis, i.e. its x and y are zero')


def test_the_finger_gap_brackets_the_part():
    """Open must clear the part, closed must press it. Measured, not assumed."""
    import mujoco
    model, data = rig.load(rig.DEFAULT_FRICTION)
    b = rig.ids(model)
    grip = model.actuator(rig.GRIPPER_ACTUATOR).id
    gaps = {}
    for ctrl in (0.0, 255.0):
        mujoco.mj_resetData(model, data)
        data.qpos[b['arm_qadr']] = model.key_qpos[0][:7]
        data.qpos[b['finger_qadr']] = model.key_qpos[0][7:9]
        data.ctrl[:] = model.key_ctrl[0]
        data.ctrl[grip] = ctrl
        mujoco.mj_forward(model, data)
        for _ in range(6000):
            mujoco.mj_step(model, data)
        gaps[ctrl] = rig.finger_gap(model, data)
    width = 2.0 * rig.PAYLOAD_HALF[0]
    assert gaps[0.0] < width < gaps[255.0], (
        f'closed gap {gaps[0.0]:.4f} must be under the part width {width:.4f}, and open '
        f'{gaps[255.0]:.4f} must be over it')


def test_the_part_is_tall_enough_for_the_fingers_to_clear_the_surface():
    """The derived constraint that the first part did NOT satisfy.

    The fingers reach 21.6 mm below the grasp frame. A grasp centred on a short part drives
    the fingertip into the work surface, and the friction there stops the gripper closing --
    at mu=1.0 that made the grip FAIL while mu=0.6 passed, which is a physically correct but
    very confusing result, and it wasted a whole round.
    """
    model, data, achieved, lowest = _grasp_pose_achieved()
    reach = achieved[2] - lowest
    need = rig.TABLE_TOP_Z + reach
    assert REST_Z >= need - 1e-9, (
        f'the grasp frame sits at {REST_Z:.4f} but the fingers reach {reach * 1000:.2f} mm '
        f'below it, so they only clear the surface above {need:.4f}')


def test_the_gripper_does_not_touch_the_table_at_the_grasp_pose():
    model, data, achieved, lowest = _grasp_pose_achieved()
    contacts = rig.contacts_between(model, data, rig.ids(model)['gripper_bodies'],
                                    rig.ids(model)['table'])
    assert lowest > rig.TABLE_TOP_Z, (
        f'the lowest gripper vertex is at {lowest:.4f}, below the table top '
        f'{rig.TABLE_TOP_Z:.4f}')
    assert not contacts, f'the gripper is already touching the table: {contacts}'


def test_the_payload_is_a_free_body_and_no_equality_references_it():
    """The anti-fake-attach condition, checked at model level."""
    import mujoco
    model, data = rig.load(rig.DEFAULT_FRICTION)
    b = rig.ids(model)
    assert any(model.jnt_type[j] == mujoco.mjtJoint.mjJNT_FREE
               and int(model.jnt_bodyid[j]) == b['payload'] for j in range(model.njnt)), \
        'the payload must be a free body'
    for e in range(model.neq):
        ids = {int(model.eq_obj1id[e]), int(model.eq_obj2id[e])}
        assert b['payload'] not in ids and b['payload_joint'] not in ids, (
            f'equality {e} references the payload: a planned attach must not be able to '
            f'stand in for contact')
    # and the gripper's own coupling must still be there, so the check above is not vacuous
    assert model.neq >= 1, (
        'the upstream gripper couples its two finger joints; if that equality is gone this '
        'test is no longer demonstrating anything about scoping')


def test_the_arm_never_moves_the_payload_by_anything_but_contact():
    """A source-level guarantee, in two halves.

    The arm's OWN joints are initialised from the home keyframe -- that is setup, and
    TEST_AND_ACCEPTANCE permits ground truth for initialisation. What must never happen is the
    PAYLOAD's state being written: a teleport, or a keyframe reset that lands on the free
    joint. The second one actually happened here (`mj_resetDataKeyframe` pads a 9-value
    keyframe out to nq=16, and the padding hit the payload), so it is worth a standing guard.
    """
    src = (ROOT / 'experiments' / 'probe_arm.py').read_text(encoding='utf-8')
    tree = ast.parse(src)
    # Comments and docstrings are not AST nodes, so the explanation of this very bug does not
    # trip the guard -- a plain substring search did.
    calls = [ast.unparse(n) for n in ast.walk(tree)
             if isinstance(n, ast.Call)
             and getattr(getattr(n, 'func', None), 'attr', None) == 'mj_resetDataKeyframe']
    assert not calls, (
        f'the probe calls {calls}: in a merged model a keyframe reset can write the payload '
        f'free joint, which moves the part without contact')
    marker = 'while data.time < SIM_SECONDS_MAX:'
    loop_line = src[:src.index(marker)].count(chr(10)) + 1
    offenders = []
    for n in ast.walk(tree):
        if not isinstance(n, ast.Assign):
            continue
        for t in n.targets:
            if isinstance(t, ast.Subscript) and 'qpos' in ast.unparse(t.value) \
                    and 'payload' in ast.unparse(t.slice) and n.lineno >= loop_line:
                offenders.append(f'line {n.lineno}: {ast.unparse(n)}')
    assert not offenders, (
        f'the probe assigns to the payload qpos INSIDE the control loop: {offenders}. '
        f'Ground truth may place the part before the run -- TEST_AND_ACCEPTANCE permits that '
        f'-- but once the machine is running, only contact may move it.')


def test_ik_converges_to_every_planned_pose_and_refuses_the_impossible():
    import mujoco
    model, data = rig.load(rig.DEFAULT_FRICTION)
    b = rig.ids(model)
    q = list(model.key_qpos[0][:7])
    worst = 0.0
    for name, target in rig.planned_poses().items():
        q, pe, re = rig.ik(model, data, target, q_seed=q)
        worst = max(worst, pe, re)
    assert worst < 1e-3, f'worst IK residual {worst:.2e}'
    with pytest.raises(RuntimeError):
        rig.ik(model, data, (3.0, 3.0, 3.0), q_seed=q)


