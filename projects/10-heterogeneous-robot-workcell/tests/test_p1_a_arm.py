"""Contract tests for PROBE-A: the rig, the geometry it derives, and the judge.

Two jobs, and the second is the one that keeps the first honest:

  * **the rig's derived quantities are what they claim to be** -- the grasp frame is a
    constant of the model, the finger stroke brackets the part, the part is tall enough for
    the fingers to clear the surface, and the upstream asset is untouched;
  * **the judge can FAIL.** Every criterion is fed a synthetic input that MUST produce FAIL
    (no contact, never leaves the table, dragged along the surface, drifts after release,
    still gripped at the end, skipped a stage, and a world that welds the part to something).
    A check that cannot be shown to fail is not a check -- the C branch shipped a permanently
    false sequence check for a whole round because nothing ever tried to break it.
"""
