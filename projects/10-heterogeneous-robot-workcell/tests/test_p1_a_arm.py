def _grasp_pose_achieved():
    """Put the arm at the grasp pose and return (model, data, achieved point, lowest z)."""
    import mujoco
    model, data = rig.load(rig.DEFAULT_FRICTION)
    plan = mujoco.MjData(model)
    b = rig.ids(model)
    mujoco.mj_resetData(model, data)
    data.qpos[b['arm_qadr']] = model.key_qpos[0][:7]
    data.qpos[b['finger_qadr']] = model.key_qpos[0][7:9]
    data.ctrl[:] = model.key_ctrl[0]
    mujoco.mj_forward(model, data)
    for _ in range(1000):
        mujoco.mj_step(model, data)
    rot = rig.home_hand_rot(model, plan)
    target = (PICK[0], PICK[1], REST_Z)
    plan.qpos[:] = data.qpos
    q, _, _ = rig.ik(model, plan, target, target_rot=rot,
                     q_seed=list(data.qpos[b['arm_qadr']]))
    data.ctrl[b['arm_dof']] = q
    for _ in range(600):
        mujoco.mj_step(model, data)
    return model, data, rig.grasp_point(model, data), rig.gripper_min_world_z(model, data)


