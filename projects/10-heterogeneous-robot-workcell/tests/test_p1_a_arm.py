def _rec(state, t, payload, grasp, grip=(), tbl=4, speed=0.0, palm=0):
    return {'t': t, 'state': state, 'payload': list(payload), 'grasp': list(grasp),
            'payload_quat': [1.0, 0.0, 0.0, 0.0], 'payload_speed': speed,
            'arm_q': [0.0] * 7, 'finger_q': [0.02, 0.02], 'gap': 0.033,
            'grip_ctrl': 0.0, 'grip_contacts': sorted(grip), 'palm_contact_n': palm,
            'table_contact_n': tbl, 'floor_contact_n': 0, 'finger_table_contact_n': 0}


def healthy_records(n_hold=100, offset=(0.0, 0.0)):
    """A trace the judge should call PASS: picked up, carried, placed, released, steady.

    `offset` displaces the part, mirroring a run whose declared start is the pick target plus
    a perturbation. The judge cross-checks the declared start against `pick_xy + part_offset`,
    so a fixture that ignored the offset would be testing a different report shape.
    """
    dx, dy = offset
    recs, t = [], 0.0

    def run(state, count, payload, grasp, grip=(), tbl=4, speed=0.0):
        nonlocal t
        for _ in range(count):
            t += 0.02
            recs.append(_rec(state, t, payload, grasp, grip, tbl, speed))

    lifted = (PICK[0] + dx, PICK[1] + dy, REST_Z + rig.LIFT_HEIGHT)
    carried = (PLACE[0] + dx, PLACE[1] + dy, REST_Z + rig.LIFT_HEIGHT)
    placed = (PLACE[0] + dx, PLACE[1] + dy, REST_Z)
    ground = (PICK[0] + dx, PICK[1] + dy, REST_Z)
    run('APPROACH', 60, ground, (PICK[0] + dx, PICK[1] + dy, REST_Z + 0.10), ())
    run('DESCEND', 40, ground, (PICK[0] + dx, PICK[1] + dy, REST_Z), ())
    run('CLOSE', 60, ground, (PICK[0] + dx, PICK[1] + dy, REST_Z),
        ('left_finger', 'right_finger'))
    run('LIFT', 80, lifted, lifted, ('left_finger', 'right_finger'), tbl=0)
    run('CARRY', 90, carried, carried, ('left_finger', 'right_finger'), tbl=0)
    run('LOWER', 80, placed, placed, ('left_finger', 'right_finger'), tbl=4)
    run('RELEASE', 30, placed, placed, ('right_finger',), tbl=4)
    run('RETREAT', 100, placed, (PLACE[0] + dx, PLACE[1] + dy, REST_Z + rig.RETREAT_HEIGHT),
        (), tbl=4)
    run('HOLD', n_hold, placed, (PLACE[0] + dx, PLACE[1] + dy, REST_Z + rig.RETREAT_HEIGHT),
        (), tbl=4)
    return recs


def synth(tmp_path, name, runs, *, records=None, world_text=None, stages=None,
          claim='CLAIMED', requires=None):
    """Write a report + traces the judge can read, mirroring the probe's real shape."""
    run_dir = tmp_path / name
    run_dir.mkdir(parents=True, exist_ok=True)
    if world_text is None:
        world = WORLD
    else:
        world = tmp_path / f'{name}_world.xml'
        world.write_text(world_text, encoding='utf-8')
    entries = []
    for i, r in enumerate(runs):
        entry = {
            'scenario': {'name': r.get('scenario_name', 'nominal'),
                         'expect': r.get('expect', 'DONE'),
                         'in_envelope': r.get('in_envelope', True)},
            'friction': r.get('friction', 0.6),
            'final_state': r.get('final_state', 'DONE'),
            'faulted': r.get('faulted', False),
            'fell_at': r.get('fell_at'),
            # the declared start is the pick target PLUS the perturbation -- the judge
            # cross-checks exactly that, so a fixture that ignored the offset would look like
            # a run whose part was not where it said it was
            'part_offset': list(r.get('part_offset', [0.0, 0.0])),
            'initial_payload': r.get('initial_payload',
                                     [PICK[0] + r.get('part_offset', [0.0, 0.0])[0],
                                      PICK[1] + r.get('part_offset', [0.0, 0.0])[1],
                                      REST_Z]),
            'transitions': r.get('transitions',
                                 [{'state': s, 't': 0.1 * k}
                                  for k, s in enumerate(rig.COORDINATE_PATH)]),
            'stages_executed': r.get('stages_executed', list(rig.COORDINATE_PATH)),
            'payload_contact_samples': r.get('payload_contact_samples', 300),
            'sim_seconds': r.get('sim_seconds', 18.0),
            'trace_file': f'trace_{i}.json',
        }
        entries.append(entry)
        if records is not None:
            payload_records = records(r) if callable(records) else records
            (run_dir / f'trace_{i}.json').write_text(
                json.dumps({'records': payload_records}), encoding='utf-8')
    report = {
        'run_id': name,
        'world': str(world),
        'world_sha256': hashlib.sha256(world.read_bytes()).hexdigest(),
        'table_top_z': rig.TABLE_TOP_Z,
        'payload_half': list(rig.PAYLOAD_HALF),
        'payload_mass': rig.PAYLOAD_MASS,
        'pick_xy': list(PICK),
        'place_xy': list(PLACE),
        'requires': list(requires if requires is not None else rig.COORDINATE_PATH),
        'stages_in_source': list(stages if stages is not None
                                 else rig.COORDINATE_PATH),
        'full_A_acceptance': claim,
        'scope_claim': 'A FIXED-ARM COMPONENT; stand-in work surface.',
        'runs': entries,
        'thresholds': {
            'min_contact_samples': rig.MIN_CONTACT_SAMPLES,
            'lift_margin_m': rig.LIFT_MARGIN,
            'carried_slip_max_m': rig.CARRIED_SLIP_MAX,
            'place_tol_xy_m': rig.PLACE_TOL_XY,
            'release_drift_max_m': rig.RELEASE_DRIFT_MAX,
            'release_speed_max_mps': rig.RELEASE_SPEED_MAX,
            'touchdown_tol_m': rig.TOUCHDOWN_TOL,
        },
    }
    (run_dir / 'report.json').write_text(json.dumps(report), encoding='utf-8')
    return tmp_path


def judge(tmp_path, name, runs, **kw):
    reports = synth(tmp_path, name, runs, **kw)
    done = subprocess.run([sys.executable, str(JUDGE), '--run-id', name,
                           '--reports-dir', str(reports)],
                          capture_output=True, text=True)
    acceptance = reports / name / 'acceptance.json'
    assert acceptance.is_file(), (
        f'the judge wrote no acceptance.json (rc={done.returncode}); '
        f'stderr: {done.stderr[-2000:]}')
    return done.returncode, json.loads(acceptance.read_text())


def verdicts(payload):
    return {c['check']: c['verdict'] for c in payload['checks']}


MUST_FAIL = {'scenario_name': 'grip_never_closes', 'expect': 'GRIP_FAILED',
             'final_state': 'GRIP_FAILED', 'faulted': True}


OFFSETS = [{'part_offset': [0.0, 0.005]}, {'part_offset': [0.005, 0.0]},
           {'part_offset': [0.004, -0.006]}]


def test_a_healthy_run_passes_every_check(tmp_path):
    # The arm carries a declared failure on purpose. Without it the judge reports the
    # falsifiability check as NOT_RUN, and the artifact is INCOMPLETE rather than PASS --
    # which is the correct behaviour and is asserted separately below. It also carries three
    # distinct part placements, because one pose repeated is not repeatability.
    # OUTSIDE is required too: without a run beyond the declared envelope the judge
    # reports that check as NOT_RUN -- correct, because a boundary nothing is run
    # against is an assumption -- and the artifact comes out INCOMPLETE, not PASS.
    OUTSIDE = {'scenario_name': 'part_shift_x_p5', 'in_envelope': False}
    rc, payload = judge(tmp_path, 'a_healthy',
                        [{}] + OFFSETS + [dict(MUST_FAIL), OUTSIDE],
                        records=lambda r: healthy_records(
                            offset=tuple(r.get('part_offset', (0.0, 0.0)))))
    assert payload['verdict'] == 'PASS', json.dumps(verdicts(payload), indent=1)
    assert rc == 0


def test_an_arm_with_no_declared_failure_is_incomplete_not_pass(tmp_path):
    """Falsifiability: an all-green judge that has never been shown a failure is INCOMPLETE."""
    rc, payload = judge(tmp_path, 'a_no_bad_case', [{}], records=healthy_records())
    assert verdicts(payload)['a case that must fail does fail'] == 'NOT_RUN'
    assert payload['verdict'] == 'INCOMPLETE'


def test_the_fixture_is_actually_reaching_the_judge(tmp_path):
    """If the fixture silently failed to load, every must-FAIL test below would pass."""
    rc, payload = judge(tmp_path, 'a_reach', [{}], records=healthy_records())
    names = {c['check'] for c in payload['checks']}
    assert 'the gripper really touches the payload' in names
    assert verdicts(payload)['the gripper really touches the payload'] == 'PASS'
    rc, payload = judge(tmp_path, 'a_reach2', [{}], records=[])
    assert verdicts(payload)['the gripper really touches the payload'] == 'FAIL', (
        'with no records at all the contact check must FAIL, not silently pass')


